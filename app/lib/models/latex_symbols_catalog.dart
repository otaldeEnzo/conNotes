enum LatexSymbolCategory {
  algebra,
  calculus,
  linearAlgebra,
  greek,
  logicSets,
  trigHyperbolic,
  delimiters,
  physicsGeometry,
}

extension LatexSymbolCategoryExtension on LatexSymbolCategory {
  String get label {
    switch (this) {
      case LatexSymbolCategory.algebra:
        return 'Álgebra';
      case LatexSymbolCategory.calculus:
        return 'Cálculo';
      case LatexSymbolCategory.linearAlgebra:
        return 'Álgebra Linear';
      case LatexSymbolCategory.greek:
        return 'Grego';
      case LatexSymbolCategory.logicSets:
        return 'Lógica & Conjuntos';
      case LatexSymbolCategory.trigHyperbolic:
        return 'Trig & Hiperbólica';
      case LatexSymbolCategory.delimiters:
        return 'Delimitadores';
      case LatexSymbolCategory.physicsGeometry:
        return 'Física & Geometria';
    }
  }
}

