/// Helper function to search symbols across the catalog.
List<LatexSymbolItem> searchLatexSymbols({
  String query = '',
  LatexSymbolCategory? category,
}) {
  final cleanQuery = query.trim().toLowerCase();

  return kLatexCatalog.where((item) {
    if (category != null && item.category != category) {
      return false;
    }

    if (cleanQuery.isEmpty) {
      return true;
    }

    if (item.label.toLowerCase().contains(cleanQuery)) {
      return true;
    }

    if (item.latex.toLowerCase().contains(cleanQuery)) {
      return true;
    }

    for (final kw in item.keywords) {
      if (kw.toLowerCase().contains(cleanQuery)) {
        return true;
      }
    }

    return false;
  }).toList();
}
